"""过渡语检测与重试指令 — 主对话模型的"假行动"防护。

模型偶尔只说"我要去做"而不真的调工具，Core 会把这句当最终答案
（纯文本 = 结束），用户看到"他说去查但没结果"（2026-11-24 真实生产问题，
最初在 GatewayModelProvider 内实现；提取到本模块供多个 Provider 复用）。

只匹配明确的行动承诺元话语，且整段很短——长回答里的"我会尽快查询"不算。
"""

from __future__ import annotations

import re

STALL_RE = re.compile(
    r"^\s*(好的|行|嗯|收到|明白|ok)?[，,。\s]*"
    r"(我(去|来|马上|这就|现在|先)?"
    r"(查|看|试|找|确认|检查|调用|执行|弄|办|处理|看看|查查|试试|找找|试试看)"
    r"(一下|一查|看|吧|咯|嘛)?|"
    r"让(我|俺)(看看|查查|试试|找找)|稍等|等一下|请稍候)"
    r"[。！!~\s…]*$",
    re.IGNORECASE,
)
STALL_NUDGE = "请直接调用工具执行，不要只描述你要做什么，然后给出最终结果。"


def is_stall_text(text: str) -> bool:
    """判断一段模型输出是否为"只承诺行动、没有实际结果"的过渡语。"""
    return bool(STALL_RE.match(text or ""))
